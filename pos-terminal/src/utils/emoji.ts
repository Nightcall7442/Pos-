export function productEmoji(name: string, categoryName = ""): string {
  for (const [pattern, emoji] of BY_NAME) if (pattern.test(name)) return emoji;
  for (const [pattern, emoji] of BY_CATEGORY) if (pattern.test(categoryName)) return emoji;
  return "🛒";
}

export function categoryEmojiShop(name: string): string {
  for (const [pattern, emoji] of BY_CATEGORY) if (pattern.test(name)) return emoji;
  return "🛒";
}
