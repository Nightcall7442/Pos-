// Product tiles show a photo when there is one; otherwise an emoji picked from
// the product's name, then from its category. The café screen's table
// (MenuScreen) is built around burgers and pizza and falls back to a plate
// for everything else — on grocery shelves that meant a plate on every tile.

// Start / end of a word. JS's \b only knows Latin letters, so «лук\b» never
